// schoolNamesFor returns the name of each school the Edupass that issues
// appCode grants roles at, by location code: real schools for
// [config.EdupassAppCodeTW], and made-up test schools for
// [config.EdupassAppCodeTWSTG]. It returns nil for any other app code.
//
// The two sets are kept apart so that a test school can never show a real
// school's name, nor the reverse.
func schoolNamesFor(appCode config.EdupassAppCode) map[string]string {
	switch appCode {
	case config.EdupassAppCodeTW:
		return productionSchoolNames
	case config.EdupassAppCodeTWSTG:
		return stagingSchoolNames
	default:
		return nil
	}
}

